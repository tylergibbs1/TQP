// TQP TypeScript Codegen
// Generates TypeScript type definitions from a TQP manifest.

import type { Manifest, TypeDefinition, FieldDefinition, ActionDefinition } from "./types";

export function generateTypes(manifest: Manifest): string {
  const lines: string[] = [];

  lines.push(`// Generated by tqp codegen from "${manifest.name}" manifest`);
  lines.push(`// TQP version: ${manifest.tqp}`);
  lines.push("");

  // Generate type interfaces
  for (const [name, typeDef] of Object.entries(manifest.types)) {
    lines.push(...generateInterface(name, typeDef));
    lines.push("");
  }

  // Generate action input/output types
  for (const [name, actionDef] of Object.entries(manifest.actions)) {
    lines.push(...generateActionTypes(name, actionDef));
    lines.push("");
  }

  // Generate action name union
  const actionNames = Object.keys(manifest.actions);
  if (actionNames.length > 0) {
    lines.push(`export type ActionName = ${actionNames.map((n) => `"${n}"`).join(" | ")};`);
    lines.push("");
  }

  return lines.join("\n");
}

function generateInterface(name: string, typeDef: TypeDefinition): string[] {
  const lines: string[] = [];
  if (typeDef.description) {
    lines.push(`/** ${typeDef.description} */`);
  }
  lines.push(`export interface ${name} {`);

  for (const [fieldName, fieldDef] of Object.entries(typeDef.fields)) {
    const optional = fieldDef.type.endsWith("?");
    const tsType = toTSType(fieldDef.type);
    const comment = buildFieldComment(fieldDef);
    if (comment) lines.push(`  ${comment}`);
    lines.push(`  ${fieldName}${optional ? "?" : ""}: ${tsType};`);
  }

  lines.push("}");
  return lines;
}

function generateActionTypes(name: string, actionDef: ActionDefinition): string[] {
  const lines: string[] = [];
  const pascalName = toPascalCase(name);

  // Input type
  if (Object.keys(actionDef.input).length > 0) {
    if (actionDef.description) {
      lines.push(`/** Input for ${name}: ${actionDef.description} */`);
    }
    lines.push(`export interface ${pascalName}Input {`);
    for (const [fieldName, fieldDef] of Object.entries(actionDef.input)) {
      const optional = !fieldDef.required;
      const tsType = toTSType(fieldDef.type);
      lines.push(`  ${fieldName}${optional ? "?" : ""}: ${tsType};`);
    }
    lines.push("}");
    lines.push("");
  }

  // Return type alias
  const returnType = toTSType(actionDef.returns);
  lines.push(`export type ${pascalName}Result = ${returnType};`);

  return lines;
}

function toTSType(tqpType: string): string {
  let t = tqpType.replace("?", "");

  if (t.startsWith("list:")) {
    const inner = toTSType(t.slice(5));
    return `${inner}[]`;
  }

  switch (t) {
    case "string":
      return "string";
    case "int":
    case "float":
      return "number";
    case "bool":
      return "boolean";
    default:
      return t; // Reference type
  }
}

function buildFieldComment(def: FieldDefinition): string | null {
  const parts: string[] = [];
  if (def.description) parts.push(def.description);
  if (def.cost === "high") parts.push("@cost high");
  if (def.deprecated) parts.push(`@deprecated ${def.deprecated}`);
  if (parts.length === 0) return null;
  return `  /** ${parts.join(" — ")} */`;
}

function toPascalCase(str: string): string {
  return str
    .split(/[_.\-\s]/)
    .map((s) => s.charAt(0).toUpperCase() + s.slice(1))
    .join("");
}
